"""Regenerate web/lib/data/wordfreq-zh.ts, the bundled Mandarin word frequencies (DESIGN §4.6).

The data is wordfreq's `large` Chinese list (subtitles, chat, web, Wikipedia and more), which is
CC BY-SA 4.0; see web/lib/data/README.md. Run it by hand when updating the list, not in CI:

    python3 -m venv /tmp/wf && /tmp/wf/bin/pip install wordfreq==3.1.1
    /tmp/wf/bin/python -I web/scripts/wordfreq-zh.py > web/lib/data/wordfreq-zh.ts

Only all-hanzi words at or above MIN_ZIPF are kept (the rest count as rare), grouped by Zipf
rounded to a tenth: one `<zipf×10>\\t<word> <word> …` line per group, most frequent first.
"""

import re
from importlib import metadata

import wordfreq

VERSION = "3.1.1"
MIN_ZIPF = 2.0
HAN = re.compile("^[\\u3400-\\u4dbf\\u4e00-\\u9fff\\uf900-\\ufaff]+$")


def main() -> None:
    assert metadata.version("wordfreq") == VERSION, metadata.version("wordfreq")
    groups: dict[int, list[str]] = {}
    # get_frequency_list returns buckets of one centibel each, most frequent first.
    for i, words in enumerate(wordfreq.get_frequency_list("zh", wordlist="large")):
        zipf = 9 - i / 100
        if zipf < MIN_ZIPF:
            break
        tenth = round(zipf * 10)
        for w in words:
            if HAN.match(w):
                groups.setdefault(tenth, []).append(w)
    lines = [f"{t}\t{' '.join(ws)}" for t, ws in sorted(groups.items(), reverse=True)]
    print(
        "// Generated by web/scripts/wordfreq-zh.py from wordfreq "
        + VERSION
        + " (zh, large). Do not edit.\n"
        "// Data CC BY-SA 4.0 (Robyn Speer, wordfreq; includes SUBTLEX-CH, Brysbaert et al.,\n"
        "// freely available): see web/lib/data/README.md.\n"
        f"export const WORDFREQ_ZH_MIN_ZIPF = {MIN_ZIPF};\n"
        "export const WORDFREQ_ZH =\n  "
        + repr("\n".join(lines)).replace("'", '"')
        + ";"
    )


if __name__ == "__main__":
    main()
